/**
 * ============================================================================
 *  symbolGroups.ts —— 符号面板的数据源（纯数据，不依赖 React）
 * ----------------------------------------------------------------------------
 *  分组的唯一职责是「让人找得到」：
 *   · 希腊字母拆成 小写 / 大写 / 变体 三组 —— 大写里与拉丁字母同形的 13 个
 *     直接写字母本身才是正确 LaTeX，而不是 \Alpha 这种不存在的命令；
 *   · 按使用场景（箭头、关系、集合、大算子、装饰、定界符、字体、几何）分组，
 *     而不是按「数学分支」，学生找 ≤ 时不会先想它属于哪一门；
 *   · 每组条目数固定展示在侧栏，找符号时有预期。
 * ============================================================================
 */

export interface Sym {
  label: string
  insert: string
  name: string
}

export interface Group {
  key: string
  title: string
  items: Sym[]
}

